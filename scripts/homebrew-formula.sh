# Prints the Homebrew formula for a kubeswitch release:
#
#   scripts/homebrew-formula.sh v1.2.3 > kubeswitch.rb
#
# The formula installs the release archives, so it carries their SHA-256
# checksums. They are read from the release's checksums.txt on GitHub,
# or from the file given as second argument, such as dist/checksums.txt
# after "make dist" (which is what "make formula" does). The Homebrew
# workflow runs this for every release and pushes the result to the tap,
# see .github/workflows/homebrew.yml.
#
# Settings (environment variables):
#   KUBESWITCH_REPO  GitHub repository of the releases (default: Yanni8/kubeswitch)
set -eu

repo="${KUBESWITCH_REPO:-Yanni8/kubeswitch}"

fail() { printf 'homebrew-formula.sh: %s\n' "$*" >&2; exit 1; }

[ $# -ge 1 ] && [ $# -le 2 ] || fail "usage: scripts/homebrew-formula.sh VERSION [CHECKSUMS]"
version=$1
case "$version" in
  [0-9]*) version="v$version" ;; # tags carry a v prefix
esac
# Homebrew reads the version off the /vX.Y.Z/ segment of the archive
# URLs, which does not work for a pre-release tag such as v1.3.0-rc1
# (its audit rejects such URLs anyway), so only release tags are accepted.
printf '%s\n' "$version" | grep -Eq '^v[0-9]+(\.[0-9]+)+$' ||
  fail "the version must be a release tag such as v1.2.3, got \"$version\" (pre-releases are not published to Homebrew)"
base="https://github.com/$repo/releases/download/$version"

if [ $# -eq 2 ]; then
  sums=$(cat "$2") || fail "could not read $2"
else
  sums=$(curl -fsSL "$base/checksums.txt") || fail "could not download $base/checksums.txt (is $version released?)"
fi

# checksum prints the SHA-256 of the archive for a platform such as darwin_arm64.
checksum() {
  sum=$(printf '%s\n' "$sums" | awk -v name="kubeswitch_$1.tar.gz" '$2 == name { print $1; exit }')
  [ "${#sum}" -eq 64 ] || fail "no SHA-256 for kubeswitch_$1.tar.gz in checksums.txt"
  printf '%s' "$sum"
}

darwin_amd64=$(checksum darwin_amd64)
darwin_arm64=$(checksum darwin_arm64)
linux_amd64=$(checksum linux_amd64)
linux_arm64=$(checksum linux_arm64)

# No "version" line: Homebrew takes the version from the URLs and rejects
# a formula that repeats it.
cat <<FORMULA
# Copyright 2026 Yannick Müller
# SPDX-License-Identifier: Apache-2.0
#
# Generated by scripts/homebrew-formula.sh in https://github.com/$repo
# for release $version. Do not edit by hand.
class Kubeswitch < Formula
  desc "Fast kubeconfig switcher with a terminal color per config"
  homepage "https://github.com/$repo"
  license "Apache-2.0"

  on_macos do
    on_intel do
      url "$base/kubeswitch_darwin_amd64.tar.gz"
      sha256 "$darwin_amd64"
    end
    on_arm do
      url "$base/kubeswitch_darwin_arm64.tar.gz"
      sha256 "$darwin_arm64"
    end
  end

  on_linux do
    on_intel do
      url "$base/kubeswitch_linux_amd64.tar.gz"
      sha256 "$linux_amd64"
    end
    on_arm do
      url "$base/kubeswitch_linux_arm64.tar.gz"
      sha256 "$linux_arm64"
    end
  end

  def install
    bin.install "kubeswitch"
    generate_completions_from_executable(bin/"kubeswitch", "completion")
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/kubeswitch version")
  end
end
FORMULA
